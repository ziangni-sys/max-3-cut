class GadgetLP:
    def __init__(self, groups, k, seed=0, verbose=True):
        self.k = k
        self.groups = groups
        self.rng = np.random.default_rng(seed)
        self.verbose = verbose
        self.Y = allowed_global_assignments(k)
        self.X = list(product(range(k), repeat=3))
        # variable layout
        self.woff = []
        off = 0
        for g in groups:
            self.woff.append(off)
            off += g.E
        self.nw = off
        self.c_idx = [off + gi for gi in range(len(groups))]
        off += len(groups)
        self.s1_idx = {i: off + i for i in range(k)}
        off += k
        self.s2_idx = {i: off + i for i in range(k)}
        off += k
        self.tau_idx = off
        off += 1
        self.nvar = off
        self.member_group = {}
        for gi, g in enumerate(groups):
            for (i, perm) in g.members:
                assert i not in self.member_group, 'each predicate needs exactly one gadget'
                self.member_group[i] = (gi, perm)
        assert sorted(self.member_group) == list(range(k))
        self._build()
        self.rowset = set()

    def _build(self):
        h = highspy.Highs()
        h.setOptionValue('output_flag', False)
        h.setOptionValue('presolve', 'off')
        inf = highspy.kHighsInf
        lower = np.zeros(self.nvar)
        upper = np.full(self.nvar, inf)
        cost = np.zeros(self.nvar)
        cost[self.tau_idx] = 1.0
        h.addVars(self.nvar, lower, upper)
        h.changeColsCost(self.nvar, np.arange(self.nvar, dtype=np.int32), cost)
        self.h = h
        k = self.k
        # completeness rows: cut(w; canon) - c_g >= 0
        for gi, g in enumerate(self.groups):
            A = g.cut_coeffs(g.completeness_colorings())
            for row in A:
                idx = list(self.woff[gi] + np.nonzero(row)[0]) + [self.c_idx[gi]]
                val = list(row[row != 0]) + [-1.0]
                self._add_row(idx, val, 0.0, inf)
        # normalization: sum_i c_{group(i)} >= 1
        cnt = {}
        for i, (gi, _) in self.member_group.items():
            cnt[gi] = cnt.get(gi, 0) + 1
        self._add_row([self.c_idx[gi] for gi in cnt], [float(cnt[gi]) for gi in cnt], 1.0, inf)
        # tau >= sum_j s2_j + s1_r - s2_r
        for r in range(k):
            idx = [self.tau_idx] + [self.s2_idx[j] for j in range(k) if j != r] + [self.s1_idx[r]]
            val = [1.0] + [-1.0] * (k - 1) + [-1.0]
            self._add_row(idx, val, 0.0, inf)

    def _add_row(self, idx, val, lo, hi):
        idx = np.asarray(idx, dtype=np.int32)
        val = np.asarray(val, dtype=np.float64)
        self.h.addRow(lo, hi, len(idx), idx, val)

    def add_sound_row(self, i, x, col_base):
        """col_base: full coloring of the *base* vertex set of i's group."""
        gi, perm = self.member_group[i]
        g = self.groups[gi]
        key = (i, tuple(int(c) for c in col_base))
        if key in self.rowset:
            return False
        self.rowset.add(key)
        coef = g.cut_coeffs(col_base)
        nz = np.nonzero(coef)[0]
        sidx = self.s1_idx[i] if sum(x) % self.k == i else self.s2_idx[i]
        self._add_row([sidx] + list(self.woff[gi] + nz), [1.0] + [-1.0] * len(nz), 0.0, highspy.kHighsInf)
        return True

    def solve(self):
        self.h.run()
        st = self.h.getModelStatus()
        if st != highspy.HighsModelStatus.kOptimal:
            raise RuntimeError(str(st))
        sol = np.array(self.h.getSolution().col_value)
        self.sol = sol
        return sol

    def weights(self, gi, sol=None):
        sol = self.sol if sol is None else sol
        g = self.groups[gi]
        return np.maximum(sol[self.woff[gi]:self.woff[gi] + g.E], 0.0)

    # --- separation -------------------------------------------------------
    def separation_items(self, gi):
        """All (i, x, y_base) the base gadget of group gi must be evaluated on."""
        g = self.groups[gi]
        items = {}
        for (i, perm) in g.members:
            for x in self.X:
                for y in self.Y:
                    yb = tuple(y[perm[j]] for j in range(self.k))
                    items.setdefault((x, yb), []).append(i)
        return items

    def separate(self, heuristic=True, restarts=8, rounds=3, tol=1e-7, max_add=None, exact_solver=None):
        sol = self.sol
        added = 0
        worst = 0.0
        k = self.k
        for gi, g in enumerate(self.groups):
            w = self.weights(gi)
            W = g.W_from_w(w)
            items = self.separation_items(gi)
            keys = list(items)
            fixed = np.array([list(x) + list(yb) for (x, yb) in keys], dtype=np.int64)
            if heuristic:
                vals, cols = batched_local_search(W, k, fixed, 3 + k, restarts=restarts,
                                                  rounds=rounds, rng=self.rng)
            else:
                vals, cols = exact_solver(gi, W, keys)
            viol = []
            for (x, yb), v, col in zip(keys, vals, cols):
                for i in items[(x, yb)]:
                    s = sol[self.s1_idx[i]] if sum(x) % k == i else sol[self.s2_idx[i]]
                    if v > s + tol:
                        viol.append((v - s, i, x, col))
            viol.sort(key=lambda t: -t[0])
            if max_add:
                viol = viol[:max_add]
            for d, i, x, col in viol:
                if self.add_sound_row(i, x, col):
                    added += 1
                    worst = max(worst, d)
        return added, worst

    def run(self, max_iter=200, restarts=8, rounds=3, max_add=None, log_every=1, time_limit=None):
        t0 = time.time()
        # seed rows: random colorings for every (i, x, y)
        for gi, g in enumerate(self.groups):
            items = self.separation_items(gi)
            for (x, yb), iis in items.items():
                col = list(x) + list(yb) + list(self.rng.integers(0, self.k, size=g.n - 3 - self.k))
                for i in iis:
                    self.add_sound_row(i, x, col)
        for it in range(max_iter):
            self.solve()
            tau = self.sol[self.tau_idx]
            added, worst = self.separate(restarts=restarts, rounds=rounds, max_add=max_add)
            if self.verbose and it % log_every == 0:
                print(f'  it {it}: tau={tau:.6f} added={added} worst_viol={worst:.3g} rows={len(self.rowset)} t={time.time()-t0:.0f}s', flush=True)
            if added == 0:
                break
            if time_limit and time.time() - t0 > time_limit:
                break
        self.solve()
        return self.sol[self.tau_idx]


