"""Column-restricted TSSW-style LP for 3LIN(k) -> MAX-k-CUT gadgets, with row generation.

Setup (NRT framework, see core.py): a gadget *group* has a base gadget for predicate i_b
(x1+x2+x3 = i_b mod k) with vertices: 3 primaries, k globals, and auxiliary vertices
indexed by *columns* f: C_{i_b} -> Z_k (the canonical witness: on satisfying x with
y = y0, aux vertex u takes the value f_u(x)).  Derived gadgets of the group are the
base gadget with the globals renamed (vertex 3+j -> 3+perm[j]); by a color-shift /
negation symmetry they inherit the base completeness on their own predicate (this is
re-checked by the exact verifier at the end).

LP (homogeneous, normalized sum_i C_i = 1):
  min tau
  s.t.  completeness:  cut_val(w; canonical coloring at x) >= c_b   for x in C_{i_b}
        sum over all gadgets i of c_{group(i)} >= 1
        tau >= sum_j s2_j + s1_r - s2_r                             for every r
        soundness rows: cut_val(w; col) <= s1_i (x in C_i) or s2_i (x in S_i)
        w >= 0
The optimum tau equals the hardness ratio of Thm A.4 *if* the soundness rows are
complete; rows are generated by (heuristic, then exact) separation.
"""
import time
from itertools import product
import numpy as np
import highspy

from .core import (allowed_global_assignments, sat_assignments, FixedMaxCut,
                   gadget_params, hardness_ratio, relabel_globals)


def inv_mod(a, k):
    for b in range(k):
        if (a * b) % k == 1:
            return b
    raise ValueError


class Group:
    def __init__(self, k, base_i, columns, derived=()):
        """columns: list of tuples of length k^2 (values of the aux vertex on
        sat_assignments(k, base_i), in that order).  derived: list of (i, perm)."""
        self.k = k
        self.base_i = base_i
        self.sat = sat_assignments(k, base_i)
        cols = []
        seen = set()
        prim = [tuple(x[j] for x in self.sat) for j in range(3)]
        const = [tuple([c] * len(self.sat)) for c in range(k)]
        for f in columns:
            f = tuple(int(v) for v in f)
            assert len(f) == len(self.sat)
            if f in seen or f in prim or f in const:
                continue
            seen.add(f)
            cols.append(f)
        self.columns = cols
        self.vcols = prim + const + cols          # column of every vertex
        self.n = len(self.vcols)
        self.derived = list(derived)
        self.members = [(base_i, list(range(k)))] + self.derived
        iu, iv = np.triu_indices(self.n, 1)
        self.eu, self.ev = iu, iv
        self.E = len(iu)

    def cut_coeffs(self, col):
        """col: (..., n) colorings -> (..., E) cut indicators on the edges."""
        col = np.asarray(col)
        return (col[..., self.eu] != col[..., self.ev]).astype(np.float64)

    def completeness_colorings(self):
        V = np.array(self.vcols)        # n x |sat|
        return V.T                      # |sat| x n

    def W_from_w(self, w):
        W = np.zeros((self.n, self.n))
        W[self.eu, self.ev] = w
        W[self.ev, self.eu] = w
        return W


def shift_perm(k, i):
    """Global renaming turning the 0-gadget into an i-gadget (needs gcd(3,k)=1)."""
    t = (i * inv_mod(3, k)) % k
    return [(j + t) % k for j in range(k)]


def make_single_group(k, columns):
    assert np.gcd(3, k) == 1
    derived = [(i, shift_perm(k, i)) for i in range(1, k)]
    return [Group(k, 0, columns, derived)]


