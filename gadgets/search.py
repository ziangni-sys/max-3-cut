def integerize(w, scale, m=None):
    """Round weights to integers; m = common normalizer (use the max over *all*
    groups, since the ratio depends on the relative scale of different gadgets)."""
    m = w.max() if m is None else m
    return np.rint(w / m * scale).astype(np.int64)


def integerize_all(lp, scale):
    ws = [lp.weights(gi) for gi in range(len(lp.groups))]
    m = max(w.max() for w in ws)
    return [integerize(w, scale, m) for w in ws]


def full_gadget_matrices(lp, int_weights):
    """Return {i: integer matrix of the i-gadget} from per-group integer weight vectors."""
    out = {}
    for gi, g in enumerate(lp.groups):
        Wb = np.zeros((g.n, g.n), dtype=np.int64)
        Wb[g.eu, g.ev] = int_weights[gi]
        Wb[g.ev, g.eu] = int_weights[gi]
        for (i, perm) in g.members:
            out[i] = Wb if perm == list(range(lp.k)) else relabel_globals(Wb, lp.k, perm)
    return out


def prune_isolated(W, k):
    """Drop auxiliary vertices with no edges (keeps primaries and globals)."""
    keep = [u for u in range(W.shape[0]) if u < 3 + k or W[u].sum() > 0]
    return W[np.ix_(keep, keep)]


def exact_params(mats, k, verbose=True):
    ps = []
    for i in range(k):
        W = prune_isolated(mats[i], k)
        t0 = time.time()
        p = gadget_params(W, k, i)
        ps.append(p)
        if verbose:
            print(f'    exact i={i}: {p} n_aux={W.shape[0]-3-k} ({time.time()-t0:.1f}s)', flush=True)
    return ps, hardness_ratio(ps)


# ---------------------------------------------------------------------------
# exact separation (meet-in-the-middle; only for small numbers of used aux vertices)
# ---------------------------------------------------------------------------

def make_mitm_solver(lp, tol=1e-12):
    def solver(gi, W, keys):
        k = lp.k
        n = W.shape[0]
        used = [u for u in range(3 + k, n) if W[u].sum() > tol]
        fm = FixedMaxCut(W, k, aux=used, integer=False)
        vals, cols = [], []
        for (x, yb) in keys:
            v, z = fm.maxval(x, yb, return_arg=True)
            col = list(x) + list(yb) + [z.get(u, 0) for u in range(3 + k, n)]
            vals.append(v)
            cols.append(col)
        return np.array(vals), np.array(cols)
    return solver


def run_exact(lp, max_rounds=20, tol=1e-7):
    """After heuristic convergence: alternate exact separation and LP re-solve."""
    solver = make_mitm_solver(lp)
    for r in range(max_rounds):
        added, worst = lp.separate(heuristic=False, exact_solver=solver, tol=tol)
        lp.solve()
        if lp.verbose:
            print(f'  exact round {r}: added={added} worst={worst:.3g} tau={lp.sol[lp.tau_idx]:.7f}', flush=True)
        if added == 0:
            break
        # cheap heuristic polishing after each exact round
        lp.run(max_iter=50)
    return lp.sol[lp.tau_idx]


def witness_columns(W, k, i):
    """Columns (functions on sat_assignments(k,i)) of an exact witness of gadget W."""
    fm = FixedMaxCut(W, k)
    sat = sat_assignments(k, i)
    y0 = tuple(range(k))
    n = W.shape[0]
    Z = []
    for x in sat:
        _, z = fm.maxval(x, y0, return_arg=True)
        Z.append([z[u] for u in range(3 + k, n)])
    Z = np.array(Z)          # |sat| x n_aux
    return [tuple(Z[:, a]) for a in range(Z.shape[1])]
